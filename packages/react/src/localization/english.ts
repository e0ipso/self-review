/** English source text is its default translation; plural and custom messages stay explicit. */
function sourceMessages<const Messages extends readonly string[]>(...messages: Messages) {
  return Object.fromEntries(messages.map(message => [message, message])) as Record<
    Messages[number],
    string
  >;
}

